/*
🧠 Ejercicio 5: Área de un rectángulo

Enunciado:

Crea una función llamada areaRectangulo que reciba base 
y altura y devuelva el área.
*/

function areaRectangulo(base, altura){
	return base * altura;
}

let resultado = areaRectangulo(4, 5);
console.log("El área del rectángulo es: " + resultado);